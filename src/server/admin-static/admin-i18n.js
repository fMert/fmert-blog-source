export function t(lang, key, vars = {}) {
  const index = { en: 0, eo: 1, tr: 2 }[lang] ?? 0;
  const phrase = Object.hasOwn(phrases, key) ? phrases[key][index] : key;
  return phrase.replace(/\{(\w+)\}/g, (match, name) => vars[name] ?? match);
}

export function applyI18n(lang) {
  for (const [marker, attribute] of [
    ['data-i18n', null],
    ['data-i18n-placeholder', 'placeholder'],
    ['data-i18n-aria-label', 'aria-label'],
    ['data-i18n-title', 'title']
  ]) {
    for (const element of document.querySelectorAll(`[${marker}]`)) {
      const value = t(lang, element.getAttribute(marker));
      if (attribute) element.setAttribute(attribute, value);
      else element.textContent = value;
    }
  }
}

if (typeof window !== 'undefined') window.FmertAdminI18n = { t, applyI18n };
